"""Train and evaluate the experimental machine-allocation ranking model (Phase C).

Label: historically_selected_machine — generated by the dataset's heuristic,
NOT verified optimal factory decisions. The model learns that heuristic.

Split: time-aware by order_created_at (from orders.csv) — all candidate rows of
an order stay in one split (group integrity by order).

Excluded from features: synthetic_candidate_score (encodes the heuristic
decision directly), record identifiers (memorization), and every leakage
column in app.ml.schema.LEAKAGE_COLUMNS.

Ranking happens only among candidates that pass candidate_eligible.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.compose import ColumnTransformer
from sklearn.ensemble import RandomForestClassifier
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

from app.ml.schema import ALLOCATION_MODEL_VERSION, LEAKAGE_COLUMNS  # noqa: E402

DATASET_DIR = BACKEND.parent / "dataset" / "textile_production_scheduling_dataset"
ARTIFACT_DIR = BACKEND / "mlartifacts"
TEST_FRACTION = 0.2
RANDOM_STATE = 42

CATEGORICAL = ["process_type", "fabric_type", "color_family", "priority", "machine_type"]
NUMERIC = [
    "gsm",
    "batch_quantity_kg",
    "machine_capacity_kg_per_batch",
    "machine_nominal_rate_kg_per_hour",
    "machine_efficiency_pct",
    "machine_availability_pct",
    "setup_estimate_minutes",
    "queue_wait_estimate_minutes",
    "processing_time_estimate_minutes",
]
EXCLUDED_IDS = {"order_id", "batch_id", "candidate_machine_id", "record_type",
                "candidate_eligible", "synthetic_candidate_score"}
LABEL = "historically_selected_machine"


def rule_baselines(eligible: pd.DataFrame) -> dict[str, pd.Series]:
    """Documented simple policies: candidate-id Series of chosen machine per order."""
    out: dict[str, pd.Series] = {}
    out["fastest_estimate"] = (
        eligible.loc[eligible.groupby("order_id")["processing_time_estimate_minutes"].idxmin()]
        .set_index("order_id")["candidate_machine_id"]
    )
    out["highest_efficiency"] = (
        eligible.loc[eligible.groupby("order_id")["machine_efficiency_pct"].idxmax()]
        .set_index("order_id")["candidate_machine_id"]
    )
    # Feature-02-like score: 0.40*efficiency + 0.35*workload(faster=better) + 0.25*neutral(50)
    scored = eligible.copy()
    fastest = scored.groupby("order_id")["processing_time_estimate_minutes"].transform("min")
    scored["workload"] = 100.0 * fastest / scored["processing_time_estimate_minutes"].clip(lower=1e-6)
    scored["score"] = 0.40 * scored["machine_efficiency_pct"] + 0.35 * scored["workload"] + 0.25 * 50.0
    out["feature02_rule"] = (
        scored.loc[scored.groupby("order_id")["score"].idxmax()]
        .set_index("order_id")["candidate_machine_id"]
    )
    return out


def mrr_and_top1(chosen: pd.Series, truth: pd.Series) -> dict:
    joined = pd.DataFrame({"chosen": chosen, "truth": truth}).dropna()
    top1 = float((joined["chosen"] == joined["truth"]).mean())
    return {"top1_accuracy": round(top1, 4), "n_orders": len(joined)}


def train() -> dict:
    cand = pd.read_csv(DATASET_DIR / "allocation_candidates.csv")
    orders = pd.read_csv(DATASET_DIR / "orders.csv")[["order_id", "order_created_at"]]

    forbidden = EXCLUDED_IDS | LEAKAGE_COLUMNS | {LABEL}
    feature_cols = CATEGORICAL + NUMERIC
    overlap = set(feature_cols) & forbidden
    if overlap:
        raise SystemExit(f"FORBIDDEN FEATURES: {sorted(overlap)}")

    cand = cand.merge(orders, on="order_id", how="left")
    cand["order_created_at"] = pd.to_datetime(cand["order_created_at"])
    order_times = cand.groupby("order_id")["order_created_at"].min().sort_values()
    n_orders = len(order_times)
    cut = int(n_orders * (1 - TEST_FRACTION))
    train_orders = set(order_times.index[:cut])
    test_orders = set(order_times.index[cut:])

    tr = cand[cand["order_id"].isin(train_orders)]
    te = cand[cand["order_id"].isin(test_orders)]
    tr_el = tr[tr["candidate_eligible"] == True]  # noqa: E712
    te_el = te[te["candidate_eligible"] == True]  # noqa: E712

    pre = ColumnTransformer(
        [
            ("cat", OneHotEncoder(handle_unknown="ignore"), CATEGORICAL),
            ("num", "passthrough", NUMERIC),
        ]
    )
    model = Pipeline(
        [
            ("pre", pre),
            ("clf", RandomForestClassifier(n_estimators=200, random_state=RANDOM_STATE, n_jobs=-1, min_samples_leaf=2)),
        ]
    )
    model.fit(tr_el[feature_cols], tr_el[LABEL].astype(int))

    probs = model.predict_proba(te_el[feature_cols])
    classes = list(model.named_steps["clf"].classes_)
    pos = classes.index(1) if 1 in classes else None
    te_scores = te_el.copy()
    te_scores["prob"] = probs[:, pos] if pos is not None else 0.0
    ml_choice = (
        te_scores.loc[te_scores.groupby("order_id")["prob"].idxmax()]
        .set_index("order_id")["candidate_machine_id"]
    )

    truth = te_el.groupby("order_id")[LABEL].max().astype(bool)
    truth_machines = te_el[te_el[LABEL] == True].set_index("order_id")["candidate_machine_id"]  # noqa: E712

    results = {
        "model_version": ALLOCATION_MODEL_VERSION,
        "label": LABEL,
        "label_caveat": "Synthetic heuristic label — model learns the dataset generator's decisions, not verified optimal assignments.",
        "n_candidate_rows": len(cand),
        "n_train_rows": len(tr_el),
        "n_test_rows": len(te_el),
        "n_train_orders": len(train_orders),
        "n_test_orders": len(test_orders),
        "split": "time-aware by order_created_at; all rows of an order in one split",
        "features": {"categorical": CATEGORICAL, "numeric": NUMERIC},
        "excluded": sorted(forbidden),
        "feature_defaults": {
            col: (
                float(tr_el[col].median()) if tr_el[col].dtype.kind in "if"
                else str(tr_el[col].mode().iloc[0])
            )
            for col in CATEGORICAL + NUMERIC
        },
        "ml_ranker": mrr_and_top1(ml_choice, truth_machines),
    }
    for name, choice in rule_baselines(te_el).items():
        results[f"baseline_{name}"] = mrr_and_top1(choice, truth_machines)

    ARTIFACT_DIR.mkdir(exist_ok=True)
    joblib.dump(model, ARTIFACT_DIR / "allocation_rank_v1.joblib")
    meta = {
        **{k: results[k] for k in ("model_version", "label", "label_caveat", "split", "features", "excluded", "feature_defaults")},
        "trained_at": datetime.now(timezone.utc).isoformat(),
        "sklearn_version": sklearn.__version__,
        "metrics_heldout": {
            k: results[k] for k in results if k.startswith(("ml_ranker", "baseline_"))
        },
        "synthetic": True,
    }
    (ARTIFACT_DIR / "allocation_rank_v1.meta.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    return results


if __name__ == "__main__":
    print(json.dumps(train(), indent=2))
